/// New writes of the three types are `Custom` with the v1 descriptor (RED until the writer is switched).
TEST(SentioWideTypeEncoding, WriterUsesCustomDescriptors)
{
    for (const auto & c : WIDE_CASES)
        EXPECT_EQ(hexOf(encodeDataType(typeOf(c))), c.header_hex) << c.id;
}

/// Every container writes its 512-bit elements with the descriptor; custom-named wrappers keep their own index.
TEST(SentioWideTypeEncoding, WriterRecursesIntoContainers)
{
    tryRegisterAggregateFunctions();
    const auto & factory = DataTypeFactory::instance();
    const String u = newHeader("SentioWide_v1_UInt512");
    const String i = newHeader("SentioWide_v1_Int512");
    const String d = newHeader("SentioWide_v1_Decimal512(100,2)");
    EXPECT_EQ(hexOf(encodeDataType(factory.get("Array(UInt512)"))), "1e" + u);
    EXPECT_EQ(hexOf(encodeDataType(factory.get("Nullable(Decimal(100, 2))"))), "23" + d);
    EXPECT_EQ(hexOf(encodeDataType(factory.get("Tuple(a Int512, b String)"))), "2002" "0161" + i + "0162" "15");
    EXPECT_EQ(hexOf(encodeDataType(factory.get("Map(String, UInt512)"))), "27" "15" + u);
    EXPECT_EQ(hexOf(encodeDataType(factory.get("Variant(String, UInt512)"))), "2a02" "15" + u);
    EXPECT_EQ(hexOf(encodeDataType(factory.get("AggregateFunction(sum, UInt512)"))), "25" "00" "03" "73756d" "00" "01" + u);
    EXPECT_EQ(hexOf(encodeDataType(factory.get("SimpleAggregateFunction(max, Int512)"))), "2e" "03" "6d6178" "00" "01" + i);
    /// JSON: the typed path's type is written with the descriptor (the other JSON parameters are not pinned here).
    const String json = encodeDataType(factory.get("JSON(a Decimal(100, 2))"));
    EXPECT_NE(json.find(customHeader("SentioWide_v1_Decimal512(100,2)")), String::npos) << hexOf(json);
}

/// The reader accepts the v1 descriptors in every origin and returns the exact native type.
