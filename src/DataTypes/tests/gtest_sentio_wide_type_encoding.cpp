String unhex(std::string_view hex)
{
    String out;
    for (size_t i = 0; i + 1 < hex.size(); i += 2)
        out.push_back(static_cast<char>(std::stoi(String(hex.substr(i, 2)), nullptr, 16)));
    return out;
}

String hexOf(std::string_view bytes)
{
    static constexpr char digits[] = "0123456789abcdef";
    String out;
    for (unsigned char c : bytes)
    {
        out.push_back(digits[c >> 4]);
        out.push_back(digits[c & 15]);
    }
    return out;
}

/// 0x2C, the size as VarUInt, the name.
String customHeader(std::string_view name, size_t declared_size)
{
    WriteBufferFromOwnString out;
    out.write(char(0x2C));
    writeVarUInt(declared_size, out);
    out.write(name.data(), name.size());
    return out.str();
}

String customHeader(std::string_view name)
{
    return customHeader(name, name.size());
}

DataTypePtr typeOf(const WideCase & c)
{
    switch (c.kind)
    {
        case WideKind::UInt512:
            return std::make_shared<DataTypeUInt512>();
        case WideKind::Int512:
            return std::make_shared<DataTypeInt512>();
        case WideKind::Decimal512:
            return std::make_shared<DataTypeDecimal<Decimal512>>(c.precision, c.scale);
    }
    UNREACHABLE();
}

/// The exact identity of a decoded 512-bit type: no custom name, the type id, the 64-byte value width, the name, and for `Decimal512`
/// the precision and the scale.
void expectWideType(const DataTypePtr & got, const WideCase & c, std::string_view where)
{
    ASSERT_NE(got, nullptr) << c.id << " " << where;
    EXPECT_FALSE(got->hasCustomName()) << c.id << " " << where;
    EXPECT_EQ(got->getSizeOfValueInMemory(), 64U) << c.id << " " << where;
    switch (c.kind)
    {
        case WideKind::UInt512:
            EXPECT_EQ(got->getTypeId(), TypeIndex::UInt512) << c.id << " " << where;
            EXPECT_EQ(got->getName(), "UInt512") << c.id << " " << where;
            break;
        case WideKind::Int512:
            EXPECT_EQ(got->getTypeId(), TypeIndex::Int512) << c.id << " " << where;
            EXPECT_EQ(got->getName(), "Int512") << c.id << " " << where;
            break;
        case WideKind::Decimal512:
        {
            EXPECT_EQ(got->getTypeId(), TypeIndex::Decimal512) << c.id << " " << where;
            const auto * decimal = typeid_cast<const DataTypeDecimal<Decimal512> *>(got.get());
            ASSERT_NE(decimal, nullptr) << c.id << " " << where;
            EXPECT_EQ(decimal->getPrecision(), c.precision) << c.id << " " << where;
            EXPECT_EQ(decimal->getScale(), c.scale) << c.id << " " << where;
            EXPECT_EQ(got->getName(), fmt::format("Decimal({}, {})", c.precision, c.scale)) << c.id << " " << where;
            break;
        }
    }
}

/// Decode exactly `bytes` (trailing bytes are an error of the test input).
DataTypePtr decode(const String & bytes, BinaryTypeOrigin origin, size_t max_complexity = 0)
{
    ReadBufferFromString in(bytes);
    auto type = decodeDataType(in, origin, max_complexity);
    if (!in.eof())
        throw Exception(ErrorCodes::INCORRECT_DATA, "test input: {} bytes after the decoded type", in.available());
    return type;
}

/// The code and the message of the DB::Exception `f` throws; {0, "no exception"} when it does not throw.
template <typename F>
std::pair<int, String> errorOf(F && f)
{
    try
    {
        f();
    }
    catch (const Exception & e)
    {
        return {e.code(), e.message()};
    }
    return {0, "no exception"};
}

