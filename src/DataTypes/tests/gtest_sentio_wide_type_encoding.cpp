/// Lock: the 64-byte little-endian value payloads do not change.
TEST(SentioWideTypeEncoding, ValuePayloadsUnchanged)
{
    for (const auto & c : WIDE_CASES)
    {
        const String payload = unhex(c.payload_hex);
        ASSERT_EQ(payload.size(), 64U) << c.id;
        const auto type = typeOf(c);
        Field field;
        String text;
        switch (c.kind)
        {
            case WideKind::UInt512:
            {
                UInt512 v;
                std::memcpy(&v, payload.data(), 64);
                field = v;
                text = wide::to_string(v);
                break;
            }
            case WideKind::Int512:
            case WideKind::Decimal512:
            {
                Int512 v;
                std::memcpy(&v, payload.data(), 64);
                text = wide::to_string(v);
                if (c.kind == WideKind::Int512)
                    field = v;
                else
                    field = DecimalField<Decimal512>(Decimal512(v), c.scale);
                break;
            }
        }
        EXPECT_EQ(text, c.value) << c.id;
        WriteBufferFromOwnString out;
        type->getDefaultSerialization()->serializeBinary(field, out, FormatSettings{});
        EXPECT_EQ(hexOf(out.str()), c.payload_hex) << c.id;
    }
}

